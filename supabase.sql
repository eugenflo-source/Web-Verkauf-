-- Diek Abriss – Datenbank & Storage
-- Einmal im Supabase SQL Editor ausführen. Bestehende id/created_at Spalten bleiben erhalten.

create table if not exists public.contact_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  phone text not null,
  email text,
  location text,
  service text not null,
  object_type text,
  disposal boolean not null default false,
  disposal_items text,
  message text not null,
  photo_paths jsonb not null default '[]'::jsonb,
  status text not null default 'Neu'
);

alter table public.contact_requests enable row level security;

alter table public.contact_requests add column if not exists name text;
alter table public.contact_requests add column if not exists phone text;
alter table public.contact_requests add column if not exists email text;
alter table public.contact_requests add column if not exists location text;
alter table public.contact_requests add column if not exists service text;
alter table public.contact_requests add column if not exists object_type text;
alter table public.contact_requests add column if not exists disposal boolean not null default false;
alter table public.contact_requests add column if not exists disposal_items text;
alter table public.contact_requests add column if not exists message text;
alter table public.contact_requests add column if not exists photo_paths jsonb not null default '[]'::jsonb;
alter table public.contact_requests add column if not exists status text not null default 'Neu';

drop policy if exists "Public can create requests" on public.contact_requests;
create policy "Public can create requests" on public.contact_requests
for insert to anon, authenticated
with check (true);

drop policy if exists "Staff can read requests" on public.contact_requests;
create policy "Staff can read requests" on public.contact_requests
for select to authenticated using (true);

drop policy if exists "Staff can update requests" on public.contact_requests;
create policy "Staff can update requests" on public.contact_requests
for update to authenticated using (true) with check (true);

drop policy if exists "Staff can delete requests" on public.contact_requests;
create policy "Staff can delete requests" on public.contact_requests
for delete to authenticated using (true);

