-- Storage: Der Bucket wird hier angelegt bzw. auf die benötigten Upload-Regeln
-- eingestellt. Damit ist die Einrichtung nicht mehr von einem manuellen Schritt
-- im Storage-Dashboard abhängig.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'diek-abriss-fotos',
  'diek-abriss-fotos',
  false,
  10485760,
  array['image/jpeg', 'image/png', 'image/webp', 'image/heic']
)
on conflict (id) do update set
  public = false,
  file_size_limit = 10485760,
  allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp', 'image/heic'];

-- Erlaubt öffentlichen Formularen das Hochladen, aber nur eingeloggtem Personal
-- das Lesen. Der erste Ordner muss die Anfrage-ID sein; so bleiben die Fotos
-- sauber einer Anfrage zugeordnet.
drop policy if exists "Public can upload diek photos" on storage.objects;
drop policy if exists "Kunden dürfen Fotos hochladen" on storage.objects;
create policy "Public can upload diek photos"
on storage.objects
for insert
to anon, authenticated
with check (
  bucket_id = 'diek-abriss-fotos'
  and (storage.foldername(name))[1] ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
);

drop policy if exists "Staff can read diek photos" on storage.objects;
create policy "Staff can read diek photos" on storage.objects
for select to authenticated
using (bucket_id = 'diek-abriss-fotos');

drop policy if exists "Staff can delete diek photos" on storage.objects;
create policy "Staff can delete diek photos" on storage.objects
for delete to authenticated
using (bucket_id = 'diek-abriss-fotos');
